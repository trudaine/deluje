package org.deluge.firmware2;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.lang.reflect.Field;
import java.lang.reflect.Modifier;
import org.junit.jupiter.api.Test;

/**
 * {@link Arpeggiator.Settings#resetToDefaults()} must restore exactly what the constructor builds.
 *
 * <p>Why it exists: in the C every clip owns its own {@code ArpeggiatorSettings} and {@code
 * Kit::getArpSettings} points at the active clip's (kit.cpp:787-797), so a clip switch cannot
 * inherit anything. This port shares one Settings per kit and resets it on load instead, so a field
 * added later and left out of the reset would silently reintroduce cross-clip leakage — which is
 * how a stale {@code noteProbability} of 0 came to silence a whole kit. This walks the fields
 * reflectively rather than listing them, so it fails when that happens.
 */
class ArpeggiatorSettingsResetTest {

  @Test
  void resetRestoresEveryFieldToItsConstructedValue() throws Exception {
    Arpeggiator.Settings fresh = new Arpeggiator.Settings();

    // Dirty every writable field, then reset and compare against a fresh instance.
    Arpeggiator.Settings dirty = new Arpeggiator.Settings();
    int dirtied = 0;
    for (Field f : Arpeggiator.Settings.class.getDeclaredFields()) {
      if (Modifier.isStatic(f.getModifiers())) {
        continue;
      }
      f.setAccessible(true);
      Class<?> t = f.getType();
      if (t == int.class) {
        f.setInt(dirty, 0x5EED5EED);
        dirtied++;
      } else if (t == boolean.class) {
        f.setBoolean(dirty, !f.getBoolean(dirty));
        dirtied++;
      } else if (t == byte[].class) {
        java.util.Arrays.fill((byte[]) f.get(dirty), (byte) 0x7B);
        dirtied++;
      } else if (t.isEnum()) {
        Object[] values = t.getEnumConstants();
        Object current = f.get(dirty);
        for (Object v : values) {
          if (v != current) {
            f.set(dirty, v);
            dirtied++;
            break;
          }
        }
      }
    }
    assertTrue(dirtied > 30, "the probe must actually dirty the fields, saw " + dirtied);

    dirty.resetToDefaults();

    for (Field f : Arpeggiator.Settings.class.getDeclaredFields()) {
      if (Modifier.isStatic(f.getModifiers())) {
        continue;
      }
      f.setAccessible(true);
      if (f.getType() == byte[].class) {
        byte[] expected = (byte[]) f.get(fresh);
        byte[] actual = (byte[]) f.get(dirty);
        if ("notePattern".equals(f.getName())) {
          // The pattern is regenerated from the shared PRNG, so it is not reproducible across
          // instances; what matters is that the reset regenerated it rather than keeping the dirt.
          boolean allDirt = true;
          for (byte b : actual) {
            if (b != (byte) 0x7B) {
              allDirt = false;
              break;
            }
          }
          assertTrue(!allDirt, "notePattern must be regenerated by the reset");
          continue;
        }
        org.junit.jupiter.api.Assertions.assertArrayEquals(expected, actual, f.getName());
      } else {
        assertEquals(f.get(fresh), f.get(dirty), f.getName() + " must be reset");
      }
    }
  }
}
